export type BlueprintNode = { id: string; type: string; name: string; value?: string };
export type Blueprint = { id: string; name: string; target: 'python' | 'cpp' | 'typescript'; nodes: BlueprintNode[]; edges: { from: string; to: string }[] };

export function generateSource(bp: Blueprint): string {
  const byId = new Map(bp.nodes.map(n => [n.id, n]));
  const start = bp.nodes.find(n => n.type === 'event')?.id;
  const order: BlueprintNode[] = [];
  let current = start;
  const seen = new Set<string>();
  while (current && !seen.has(current)) {
    seen.add(current); const node = byId.get(current); if (!node) break; order.push(node);
    current = bp.edges.find(e => e.from === current)?.to;
  }
  const calls = order.filter(n => n.type === 'function');
  if (bp.target === 'python') return ['# Generated by AI Second Brain', `# ${bp.id}`, '', 'def main():', ...calls.map(n => `    ${n.name}(${JSON.stringify(n.value ?? 'Hello from AI Second Brain')})`), '    return 0', '', 'if __name__ == "__main__":', '    main()'].join('\n');
  if (bp.target === 'typescript') return ['// Generated by AI Second Brain', `// ${bp.id}`, '', 'export function main(): number {', ...calls.map(n => `  ${n.name}(${JSON.stringify(n.value ?? 'Hello from AI Second Brain')});`), '  return 0;', '}', '', 'main();'].join('\n');
  return ['// Generated by AI Second Brain', `// ${bp.id}`, '#include <iostream>', '', 'int main() {', ...calls.map(n => `  std::cout << ${JSON.stringify(n.value ?? 'Hello from AI Second Brain')} << std::endl;`), '  return 0;', '}'].join('\n');
}
